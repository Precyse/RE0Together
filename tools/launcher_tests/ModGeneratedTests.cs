using CoopLauncher;

namespace LauncherTests;

/// <summary>ModInstaller with a generated folder entry on temp folders: the scripts are built from the player's own files, owned,
/// repaired, adopted and removed like the files of a folder entry, and a file that is not the supported one refuses the install.</summary>
public static class ModGeneratedTests
{
    private const string Dll = "dinput8.dll";
    private const string Scripts = "coop/scripts";
    private const string Bookkeeping = "coop/.cfmod/scripts";
    private const string RecipeName = "scripts.delta.json";

    private sealed class Failure : IProgress<ModProgress>
    {
        public string? Reason { get; private set; }

        public void Report(ModProgress value) => Reason = value.Step == ModStep.Failed ? value.Reason : Reason;
    }

    private sealed class Rig : IDisposable
    {
        public Rig(bool withRecipe = true)
        {
            Files = new ModInstallerTests.Rig(Dll);
            var (_, recipe, scripts) = ScriptDeltaTests.NewGame(Files.Root);
            Expected = scripts;
            File.Move(recipe, Path.Combine(Files.Package, RecipeName));
            if (!withRecipe) File.Delete(Path.Combine(Files.Package, RecipeName));
            Profile = Files.Profile with
            {
                AdapterFiles = ModFiles.Expand([new AdapterFile(Dll, Dll), new AdapterFile(RecipeName, Scripts, Generate: "delta")], Files.Package)
                    .Select(f => f with { Src = Path.Combine(Files.Package, f.Src) }).ToList(),
            };
        }

        /// <summary>The scripts the recipe must build, with the bytes they start from.</summary>
        public List<ScriptDeltaTests.Script> Expected { get; }
        public GameProfile Profile { get; }
        public ModInstallerTests.Rig Files { get; }
        public string Game => Files.Game;

        public byte[] Installed(string name) => File.ReadAllBytes(Files.GamePath(Scripts + "/" + name));

        public void Dispose() => Files.Dispose();
    }

    public static void Run()
    {
        InstallBuildsTheScriptsFromThePlayersFiles();
        TwoPlayersGetIdenticalBytes();
        AModifiedScriptIsRepaired();
        AnIdenticalFolderIsAdoptedWithoutBackups();
        AFileThatIsNotSupportedRefusesTheInstall();
        UninstallRemovesTheGeneratedScripts();
        AMissingRecipeIsAnIncompletePackage();
    }

    private static List<string> FolderFiles(Rig rig) =>
        Directory.GetFiles(rig.Files.GamePath(Scripts)).Select(Path.GetFileName).Order(StringComparer.Ordinal).ToList()!;

    private static void InstallBuildsTheScriptsFromThePlayersFiles()
    {
        using var rig = new Rig();
        Check.That(rig.Profile.AdapterFiles.Count == 4, "the dll and the recipe's three scripts");
        Check.That(rig.Profile.AdapterFiles[1].Dst == Scripts + "/a.lua" && rig.Profile.AdapterFiles[1].FolderDst == Scripts, "a generated entry expands to the recipe's files");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.NotInstalled, "nothing installed yet");

        Check.That(ModInstaller.Install(rig.Profile, rig.Game), "the install succeeds");
        Check.That(rig.Expected.All(script => rig.Installed(script.Name).SequenceEqual(script.Target)), "every script is the generated bytes");
        Check.That(FolderFiles(rig).SequenceEqual(["a.lua", "b.lua", "c.lua"]), "the scripts folder holds only the scripts: no marker, backup or manifest");
        Check.That(rig.Files.GameHas(Bookkeeping + "/a.lua.cfown") && rig.Files.GameHas(Bookkeeping + "/.cfmanifest"), "markers and the manifest sit beside the folder");
        Check.That(ModFiles.ParseManifest(rig.Files.ReadGame(Bookkeeping + "/.cfmanifest")).SequenceEqual(rig.Expected.Select(script => Scripts + "/" + script.Name)),
            "the manifest lists the three scripts");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.Installed, "installed");
        Check.That(!rig.Files.GameHas(Bookkeeping + "/a.lua.tmp") && !rig.Files.GameHas(Bookkeeping + "/a.lua.prev"), "no staging leftovers");
        Check.That(ModInstaller.Install(rig.Profile, rig.Game) && ModInstaller.Status(rig.Profile, rig.Game).State == ModState.Installed, "installing again changes nothing");
    }

    private static void TwoPlayersGetIdenticalBytes()
    {
        using var first = new Rig();
        using var second = new Rig();
        ModInstaller.Install(first.Profile, first.Game);
        ModInstaller.Install(second.Profile, second.Game);
        var hashes = new[] { first, second }.Select(rig => ModInstaller.ContentHash(rig.Profile, rig.Game)).ToList();
        Check.That(hashes[0] != null && hashes[0]!.SequenceEqual(hashes[1]!), "two installs from the same files give the same mod hash");
        Check.That(first.Expected.All(script => first.Installed(script.Name).SequenceEqual(second.Installed(script.Name))), "and identical script bytes");
    }

    private static void AModifiedScriptIsRepaired()
    {
        using var rig = new Rig();
        ModInstaller.Install(rig.Profile, rig.Game);
        rig.Files.SetGame(Scripts + "/b.lua", "edited by hand");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.Modified, "an edited script: modified");
        Check.That(ModInstaller.Install(rig.Profile, rig.Game), "install repairs it");
        Check.That(rig.Installed("b.lua").SequenceEqual(rig.Expected[1].Target), "the generated script is back");
        Check.That(rig.Files.ReadGame(Bookkeeping + "/b.lua.cfbak") == "edited by hand", "the edit is kept as a backup");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.Installed, "installed after the repair");
    }

    private static void AnIdenticalFolderIsAdoptedWithoutBackups()
    {
        using var rig = new Rig();
        Directory.CreateDirectory(rig.Files.GamePath(Scripts));
        foreach (var script in rig.Expected) File.WriteAllBytes(rig.Files.GamePath(Scripts + "/" + script.Name), script.Target);
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.NotInstalled, "a hand-copied folder has no markers: not installed");
        Check.That(ModInstaller.Install(rig.Profile, rig.Game), "installing over it succeeds");
        Check.That(!Directory.EnumerateFiles(rig.Game, "*.cfbak*", SearchOption.AllDirectories).Any(), "the identical scripts are adopted: no backup");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.Installed, "installed");
    }

    private static void AFileThatIsNotSupportedRefusesTheInstall()
    {
        using var rig = new Rig();
        File.AppendAllText(rig.Files.GamePath(ScriptDeltaTests.FixesFolder + "/c.lua"), "x");
        var failure = new Failure();
        Check.That(!ModInstaller.Install(rig.Profile, rig.Game, failure), "a Juiced file of another version refuses the install");
        Check.That(failure.Reason is { } reason && reason.Contains("c.lua") && reason.Contains("Fixes"), "and names the file and where it is");
        Check.That(!rig.Files.GameHas(Dll) && !rig.Files.GameHas(Scripts) && !rig.Files.GameHas("coop/.cfmod"), "nothing is written, not even the dll");

        ScriptDeltaTests.WritePack(rig.Files.GamePath(ScriptDeltaTests.PackName), [("a.lua", ScriptDeltaTests.Text("another build"))]);
        File.WriteAllBytes(rig.Files.GamePath(ScriptDeltaTests.FixesFolder + "/c.lua"), rig.Expected[2].SourceBytes);
        var packFailure = new Failure();
        Check.That(!ModInstaller.Install(rig.Profile, rig.Game, packFailure) && packFailure.Reason?.Contains(ScriptDeltaTests.PackName) == true,
            "a pack of another build refuses the install and names the pack");
        Check.That(!rig.Files.GameHas(Dll) && !rig.Files.GameHas(Scripts), "nothing is written for it either");
    }

    private static void UninstallRemovesTheGeneratedScripts()
    {
        using var rig = new Rig();
        rig.Files.SetGame(Scripts + "/b.lua", "the player's own b");
        ModInstaller.Install(rig.Profile, rig.Game);
        Check.That(rig.Files.ReadGame(Bookkeeping + "/b.lua.cfbak") == "the player's own b", "a player's script in the way is backed up");
        Check.That(ModInstaller.Uninstall(rig.Profile, rig.Game), "uninstall succeeds");
        Check.That(rig.Files.ReadGame(Scripts + "/b.lua") == "the player's own b" && FolderFiles(rig).SequenceEqual(["b.lua"]), "the original comes back and nothing else is left");
        Check.That(!rig.Files.GameHas(Dll) && !rig.Files.GameHas("coop/.cfmod"), "the dll and the bookkeeping are gone");
        Check.That(ModInstaller.Status(rig.Profile, rig.Game).State == ModState.NotInstalled, "not installed after the uninstall");
    }

    private static void AMissingRecipeIsAnIncompletePackage()
    {
        using var rig = new Rig(withRecipe: false);
        Check.That(rig.Profile.AdapterFiles.Count == 2, "a missing recipe stays one entry naming the folder");
        Check.That(!ModInstaller.Install(rig.Profile, rig.Game) && !rig.Files.GameHas(Dll), "an install without the recipe fails and installs nothing");
    }
}
