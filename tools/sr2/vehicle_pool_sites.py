"""Writes adapters/sr2/src/vehicle_pool_references.h: the exe references to the vehicle pool and its side tables (milestone 15).

usage: python tools/sr2/vehicle_pool_sites.py <SR2_pc.exe> [<output header>]

Every absolute address in the exe's code or data has an entry in its base relocation table, so the table lists every reference to
a static array. A reference is a relocation whose dword lies in a table's range (docs/SR2_NOTES.md, "Vehicle pool (milestone
15)"). The static constructors, their destructors and one end-of-pool test are classified by hand below. The script fails unless
each table has the number of references the research inventory counted (219 in all).
"""
import struct
import sys
from pathlib import Path

import pefile

SHIPPED = 32
BYTE_TABLE_TRAILER = 1 + SHIPPED  # count byte, then one stack byte per entry

# (id, name, base, element size, count byte and stack follow, expected references). Same order as vehicle_pool_sites.h.
TABLES = [
    ("Pool", "VP", 0x2FED938, 0x95A4, False, 2),
    ("T1", "T1", 0x3118DB8, 0x128, True, 28),
    ("T2", "T2", 0x311B2E0, 0x58, True, 33),
    ("T4", "T4", 0x311C218, 0x10, True, 31),
    ("T6", "T6", 0x311C570, 0x7D8, True, 32),
    ("T7", "T7", 0x312C098, 0xE0, True, 27),
    ("T8", "T8", 0x3179F70, 0xF8, True, 25),
    ("Nodes", "CN", 0x215C370, 0x1C, False, 6),
    ("SlotPointers", "CU pointers", 0x223F9F0, 4, False, 4),
    ("BuffersExt", "CU buffers ext", 0x223FA70, 0x1400, False, 1),
    ("BuffersCb", "CU buffers cb", 0x2267A70, 0x1800, False, 1),
    ("ObjectsCb", "CU A", 0x2FAAA00, 0x54, False, 15),
    ("ObjectsExt", "CU B", 0x2FAB480, 0x54, False, 14),
]

# The static constructors and their atexit destructors run on the old arrays and are left alone: they build the shipped 32.
CONSTRUCTOR_SITES = {0xDB2133, 0xDB216A, 0xDB21D6, 0xAE1C70, 0xDB1F73, 0xDB1FA3, 0xDB67A1}
# The one reference to the end of the pool (the world reset's loop test); the same value is the base of table T1.
POOL_END_SITE = 0xAE233E
EXPECTED_TOTAL = 219


def relocation_dwords(pe):
    """(address of the dword, the dword) for every HIGHLOW relocation of the exe."""
    pe.parse_data_directories([pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_BASERELOC"]])
    base = pe.OPTIONAL_HEADER.ImageBase
    for block in pe.DIRECTORY_ENTRY_BASERELOC:
        for entry in block.entries:
            if entry.type != pefile.RELOCATION_TYPE["IMAGE_REL_BASED_HIGHLOW"]:
                continue
            raw = pe.get_data(entry.rva, 4)
            if len(raw) == 4:
                yield base + entry.rva, struct.unpack("<I", raw)[0]


def table_of(site, value):
    """The table a reference belongs to, or None. A range is [base, end) of the array; the byte tables also own their count byte
    and stack. The pool's end is claimed by POOL_END_SITE alone (T1 starts where the pool ends)."""
    if site == POOL_END_SITE:
        return "Pool"
    for table_id, _, base, size, trailer, _ in TABLES:
        end = base + SHIPPED * size + (BYTE_TABLE_TRAILER if trailer else 0)
        if base <= value < end + (1 if trailer else 0):
            return table_id
    return None


def collect(pe):
    rows = {table[0]: [] for table in TABLES}
    for site, value in relocation_dwords(pe):
        if site in CONSTRUCTOR_SITES:
            continue
        table_id = table_of(site, value)
        if table_id:
            rows[table_id].append((site, value))
    return rows


def check_counts(rows):
    problems = []
    for table_id, name, _, _, _, expected in TABLES:
        found = len(rows[table_id])
        if found != expected:
            problems.append(f"{name}: {found} references, the inventory has {expected}")
    total = sum(len(table_rows) for table_rows in rows.values())
    if total != EXPECTED_TOTAL:
        problems.append(f"total {total}, the inventory has {EXPECTED_TOTAL}")
    return problems


def render(rows, exe_name):
    lines = [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        '#include "vehicle_pool_sites.h"',
        "",
        f"// Generated by tools/sr2/vehicle_pool_sites.py from {exe_name}; do not edit. One row per reference to a vehicle table:",
        "// the address of the dword and the dword the exe holds there.",
        "namespace vehicle_pool_references {",
        "",
        "struct Reference {",
        "    vehicle_pool_sites::TableId table;",
        "    uintptr_t site;",
        "    uint32_t value;",
        "};",
        "",
        "inline constexpr Reference kReferences[] = {",
    ]
    for table_id, name, *_ in TABLES:
        lines.append(f"    // {name}")
        for site, value in sorted(rows[table_id]):
            lines.append(f"    {{vehicle_pool_sites::TableId::{table_id}, 0x{site:X}, 0x{value:X}}},")
    lines += ["};", "", "}  // namespace vehicle_pool_references", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) not in (2, 3):
        print(__doc__)
        return 2
    exe = Path(argv[1])
    out = Path(argv[2]) if len(argv) == 3 else Path(__file__).resolve().parents[2] / "adapters/sr2/src/vehicle_pool_references.h"
    rows = collect(pefile.PE(str(exe), fast_load=True))
    problems = check_counts(rows)
    if problems:
        print("vehicle pool references do not match the inventory:\n  " + "\n  ".join(problems))
        return 1
    out.write_text(render(rows, exe.name), encoding="utf-8", newline="\n")
    print(f"wrote {sum(len(r) for r in rows.values())} references to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
